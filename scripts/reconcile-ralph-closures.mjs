#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * scripts/reconcile-ralph-closures.mjs — close issues whose Ralph work shipped (ops#305).
 *
 * The problem: a Ralph PR merges with `Closes #N` in its body, GitHub's
 * closing-keyword linkage silently doesn't fire, and the issue stays open and
 * `ralph-ready`. The loop re-claims it, the agent correctly reports "already
 * shipped, nothing to do", and the cycle repeats. ops#156 did this 12+ times in
 * ~12 hours; ops#103, #3, #205, #210 and #282 are the same shape.
 *
 * `CLAUDE.md` already tells humans to "verify merge state via the API, never
 * assume it merged". This makes that mechanical.
 *
 * Dry-run is the default (house pattern: fleet-dispatch.mjs, sync-preview-urls.mjs).
 * Nothing is closed without --apply.
 *
 * Usage:
 *   node scripts/reconcile-ralph-closures.mjs              # report only
 *   node scripts/reconcile-ralph-closures.mjs --apply      # close them
 *   node scripts/reconcile-ralph-closures.mjs --json       # canonical violations shape
 *
 * Env: GITHUB_TOKEN (Issues: read/write). GITHUB_REPO defaults to hirobius/ops.
 *
 * Exit codes: 0 clean/applied · 1 stale closures found (report mode) · 2 invocation error.
 *
 * @module reconcile-ralph-closures
 */

import { findStaleClosures, hasBreakableClosingKeyword } from '../lib/tasks/stale-closure.mjs';
import { authHint } from '../lib/github/issues.mjs';

const APPLY = process.argv.includes('--apply');
const JSON_MODE = process.argv.includes('--json');
const REPO = process.env.GITHUB_REPO || 'hirobius/ops';
const TOKEN = process.env.GITHUB_TOKEN;

const TOKEN_FIX =
  'GITHUB_TOKEN is not set (needs "Issues: read/write"). ' +
  'Set it in your shell for a local run, or in Vercel → Settings → Environment Variables ' +
  '(Production) and redeploy: ' +
  'https://vercel.com/adrian-6234s-projects/hirobius-ops/settings/environment-variables — ' +
  'fine-grained tokens: https://github.com/settings/personal-access-tokens';

if (!TOKEN) {
  // --json must always emit the canonical { violations } shape (the
  // audit-gates-supportjson contract). "I could not check" is reported as a
  // violation rather than silently as a clean run — an unconfigured gate that
  // returns zero findings is how a guardrail goes quietly dead (see the decay
  // rule in docs/ai/FRONTIER-DOCTRINE.md §4).
  if (JSON_MODE) {
    console.log(
      JSON.stringify({ violations: [{ id: 'missing-github-token', detail: TOKEN_FIX }] }, null, 2),
    );
    process.exit(1);
  }
  console.error(`reconcile-ralph-closures: ${TOKEN_FIX}`);
  process.exit(2);
}

const headers = {
  Authorization: `Bearer ${TOKEN}`,
  Accept: 'application/vnd.github+json',
  'User-Agent': 'hirobius-ops',
};

async function gh(url, init = {}) {
  const res = await fetch(url, { headers, signal: AbortSignal.timeout(9000), ...init });
  if (res.status === 401 || res.status === 403) throw new Error(authHint(res.status));
  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`HTTP ${res.status}${text ? ` — ${text.slice(0, 200)}` : ''}`);
  }
  return res.json();
}

/** Every closed PR whose head branch is a Ralph branch, newest first. */
async function fetchRalphPrs() {
  const out = [];
  for (let page = 1; page <= 5; page++) {
    const batch = await gh(
      `https://api.github.com/repos/${REPO}/pulls?state=closed&per_page=100&page=${page}&sort=updated&direction=desc`,
    );
    if (!batch.length) break;
    out.push(
      ...batch.map((p) => ({
        number: p.number,
        headRef: p.head?.ref ?? '',
        merged: Boolean(p.merged_at),
        body: p.body ?? '',
      })),
    );
    if (batch.length < 100) break;
  }
  return out.filter((p) => p.headRef.startsWith('ralph/issue-'));
}

/** Open issues only — the /issues endpoint mixes PRs in, so drop those. */
async function fetchOpenIssues() {
  const out = [];
  for (let page = 1; page <= 5; page++) {
    const batch = await gh(
      `https://api.github.com/repos/${REPO}/issues?state=open&per_page=100&page=${page}`,
    );
    if (!batch.length) break;
    out.push(...batch.filter((i) => !i.pull_request).map((i) => ({ number: i.number })));
    if (batch.length < 100) break;
  }
  return out;
}

async function closeIssue(number, prNumbers) {
  const refs = prNumbers.map((n) => `#${n}`).join(', ');
  await gh(`https://api.github.com/repos/${REPO}/issues/${number}/comments`, {
    method: 'POST',
    headers: { ...headers, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      body:
        `Closing as completed — the work shipped in ${refs}, but GitHub's closing-keyword ` +
        `linkage never fired, so this stayed open and the Ralph loop kept re-claiming it ` +
        `(ops#305).\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`,
    }),
  });
  await gh(`https://api.github.com/repos/${REPO}/issues/${number}`, {
    method: 'PATCH',
    headers: { ...headers, 'Content-Type': 'application/json' },
    body: JSON.stringify({ state: 'closed', state_reason: 'completed' }),
  });
}

async function main() {
  const prs = await fetchRalphPrs();
  const openIssues = await fetchOpenIssues();

  const stale = findStaleClosures({ prs, openIssues });
  // Same corpus, second signal: merged PR bodies carrying a closing keyword
  // GitHub cannot link. These are the *cause* of the stale closures above.
  const breakable = prs
    .filter((p) => p.merged && hasBreakableClosingKeyword(p.body))
    .map((p) => p.number);

  const violations = [
    ...stale.map((s) => ({
      id: `stale-closure-${s.issueNumber}`,
      detail: `issue #${s.issueNumber} is open but its work merged in ${s.prNumbers.map((n) => `#${n}`).join(', ')}`,
    })),
    ...breakable.map((n) => ({
      id: `breakable-closing-keyword-${n}`,
      detail: `PR #${n} wraps its closing reference in markdown — GitHub will not link it`,
    })),
  ];

  if (JSON_MODE) {
    console.log(JSON.stringify({ violations }, null, 2));
    process.exit(violations.length ? 1 : 0);
  }

  if (!violations.length) {
    console.log(`reconcile-ralph-closures: ${REPO} clean — no stale closures ✓`);
    process.exit(0);
  }

  for (const v of violations) console.log(`  ${v.detail}`);

  if (!APPLY) {
    console.log(
      `\nreconcile-ralph-closures: ${stale.length} stale closure(s), ${breakable.length} breakable keyword(s).` +
        `\n      dry-run — re-run with --apply to close the stale issues.`,
    );
    process.exit(1);
  }

  for (const s of stale) {
    await closeIssue(s.issueNumber, s.prNumbers);
    console.log(`  ✓ closed #${s.issueNumber}`);
  }
  console.log(`\nreconcile-ralph-closures: closed ${stale.length} issue(s).`);
  process.exit(0);
}

main().catch((err) => {
  // Same contract as the missing-token path: in --json mode every outcome —
  // including "the gate could not run" — is the canonical { violations } shape.
  // A gate that crashes into a non-JSON stderr blob is a gate downstream
  // tooling (ralph/metric.sh, audit-gates-supportjson) cannot read at all.
  if (JSON_MODE) {
    console.log(
      JSON.stringify({ violations: [{ id: 'gate-error', detail: err.message }] }, null, 2),
    );
    process.exit(1);
  }
  console.error(`reconcile-ralph-closures: ${err.message}`);
  process.exit(2);
});
